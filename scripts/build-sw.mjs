import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { cp, readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, relative, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import appPaths from '../src/routes.json' with { type: 'json' };

const collect = async (directory) => {
  const entries = await readdir(directory, { withFileTypes: true });
  const paths = await Promise.all(
    entries.map((entry) => {
      const path = resolve(directory, entry.name);
      return entry.isDirectory() ? collect(path) : path;
    }),
  );
  return paths.flat().sort();
};
export async function buildWorker(project, buildId, deploymentId = null) {
  const assets = [];
  for (const [root, prefix] of [
    [resolve(project, 'public'), '/'],
    [resolve(project, '.next/static'), '/_next/static/'],
  ]) {
    for (const file of await collect(root)) {
      const name = relative(root, file).split(sep).map(encodeURIComponent).join('/');
      if (name === 'sw.js' || name.endsWith('.map')) continue;
      assets.push({
        url: prefix + name,
        sha256: createHash('sha256')
          .update(await readFile(file))
          .digest('hex'),
      });
    }
  }
  const snapshots = {};
  for (const path of appPaths) {
    const name = path.slice(1) || 'index';
    const prefix = '/_next/static/' + buildId + '/offline/' + name;
    snapshots[path] = prefix;
  }
  for (const prefix of Object.values(snapshots)) {
    for (const extension of ['html', 'rsc']) {
      const url = prefix + '.' + extension;
      if (!assets.some((asset) => asset.url === url))
        throw new Error('Missing offline snapshot: ' + url);
    }
  }
  const version = createHash('sha256').update(JSON.stringify(assets)).digest('hex').slice(0, 20);

  const worker = `/* Generated by scripts/build-sw.mjs. */
const CACHE_PREFIX = 'stilllight-assets-';
const CACHE_NAME = CACHE_PREFIX + '${version}';
const ASSETS = ${JSON.stringify(assets)};
const BUILD_ID = ${JSON.stringify(buildId)};
const FLIGHT_HEADERS = ${JSON.stringify({ 'Content-Type': 'text/x-component', ...(deploymentId ? { 'x-nextjs-deployment-id': deploymentId } : {}) })};
const ASSET_HEADERS = ${JSON.stringify(deploymentId ? { 'x-deployment-id': deploymentId } : {})};
const SNAPSHOTS = new Map(Object.entries(${JSON.stringify(snapshots)}));
const REQUIRED_URLS = new Set(ASSETS.map((asset) => asset.url));
const digest = async (buffer) => Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256', buffer)), (byte) => byte.toString(16).padStart(2, '0')).join('');
const isComplete = async () => {
  const cache = await caches.open(CACHE_NAME);
  const results = await Promise.all(ASSETS.map(async ({ url }) => {
    const response = await cache.match(url);
    return Boolean(response && response.ok);
  }));
  return results.every(Boolean);
};
const fetchVerified = async ({ url, sha256 }) => {
  // Preserve preview authentication and keep the toolbar out of verified HTML bytes.
  const headers = url.endsWith('.html') ? { ...ASSET_HEADERS, 'x-vercel-skip-toolbar': '1' } : ASSET_HEADERS;
  const response = await fetch(new Request(url, { cache: 'reload', credentials: 'same-origin', headers }));
  if (!response.ok || await digest(await response.clone().arrayBuffer()) !== sha256) {
    throw new Error('Unable to cache required asset: ' + url);
  }
  return { url, response };
};
const restoreMissing = async () => {
  const cache = await caches.open(CACHE_NAME);
  // Storage can be evicted after installation. An online readiness check can
  // repair missing entries, but only from bytes belonging to this exact build.
  const missing = [];
  for (const asset of ASSETS) if (!(await cache.match(asset.url))) missing.push(asset);
  const responses = await Promise.all(missing.map(fetchVerified));
  await Promise.all(responses.map(({ url, response }) => cache.put(url, response)));
};

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    // Verify every response before writing. Never delete a same-version cache
    // that an existing active worker could still be using if installation fails.
    const responses = await Promise.all(ASSETS.map(fetchVerified));
    await Promise.all(responses.map(({ url, response }) => cache.put(url, response)));
    if (!(await isComplete())) throw new Error('Incomplete offline cache.');
    // No skipWaiting: an update waits until every old client closes.
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    // Activation occurs only when the previous worker has no controlled clients.
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME).map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data?.type !== 'CHECK_OFFLINE' || !event.ports[0]) return;
  event.waitUntil((async () => {
    try {
      if (!(await isComplete())) await restoreMissing();
      event.ports[0].postMessage({ type: 'OFFLINE_STATUS', ready: await isComplete(), version: '${version}' });
    } catch {
      event.ports[0].postMessage({ type: 'OFFLINE_STATUS', ready: false });
    }
  })());
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin) return;
  const navigation = event.request.mode === 'navigate';
  const snapshot = SNAPSHOTS.get(url.pathname);
  if (navigation && !snapshot) {
    event.respondWith(fetch(event.request).catch(() => {
      // Mirror Next's trailing-slash canonicalization and the app's unknown-route redirect.
      const path = url.pathname.replace(/\\/+$/, '') || '/';
      const fallback = SNAPSHOTS.has(path) ? path + url.search : '/';
      return Response.redirect(new URL(fallback, self.location.origin), 307);
    }));
    return;
  }
  const headers = event.request.headers;
  const flight = snapshot && headers.get('rsc') === '1' &&
    !headers.has('next-router-prefetch') && !headers.has('next-router-segment-prefetch') &&
    !headers.has('next-action') && [...url.searchParams.keys()].every((key) => key === '_rsc');
  if (snapshot && (navigation || flight)) {
    event.respondWith((async () => {
      let live;
      try {
        live = await fetch(event.request);
        // An open tab stays on its own build until the waiting worker activates.
        // For a matching build, always return the real request-time SSR response.
        const liveBuild = live.headers.get('x-arcana-build');
        if (live.ok && liveBuild === BUILD_ID) return live;
        // Keep client errors and redirects. A newer build can legitimately
        // remove a route that an older client is still using.
        const removedInNewBuild = live.status === 404 && liveBuild && liveBuild !== BUILD_ID;
        if (!live.ok && live.status < 500 && !removedInNewBuild) return live;
      } catch {
        // A failed request shares the same fallback as a server outage.
      }
      const cached = await (await caches.open(CACHE_NAME)).match(snapshot + (flight ? '.rsc' : '.html'));
      if (!cached) return live || Response.error();
      // Use the actual requested URL for the router. A cached response carries
      // its static file URL, which would change the target of a Flight navigation.
      return flight ? new Response(cached.body, { headers: FLIGHT_HEADERS }) : cached;
    })());
    return;
  }
  // Browsers and bundlers can use either literal or escaped brackets in page chunk names.
  let asset;
  try {
    asset = url.pathname.split('/').map((part) => encodeURIComponent(decodeURIComponent(part))).join('/');
  } catch {
    return;
  }
  if (REQUIRED_URLS.has(asset)) {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      return await cache.match(asset) || fetch(event.request);
    })());
  }
});
`;
  await writeFile(resolve(project, 'public/sw.js'), worker);
  // Vercel's Next adapter assembles its output during next build, before the
  // offline documents and worker exist. Update any previous worker too.
  const adapterOutput = resolve(project, '.next/output');
  if (existsSync(resolve(adapterOutput, 'config.json'))) {
    await cp(
      resolve(project, '.next/static', buildId, 'offline'),
      resolve(adapterOutput, 'static/_next/static', buildId, 'offline'),
      { recursive: true },
    );
    await writeFile(resolve(adapterOutput, 'static/sw.js'), worker);
  }
  console.log(
    `Built service worker ${version}: ${assets.length} required assets, verified at installation.`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const buildDir = resolve('.next');
    const buildId = (await readFile(resolve(buildDir, 'BUILD_ID'), 'utf8')).trim();
    const { writeOfflineSnapshots } = await import('./offline-snapshots.mjs');
    const deploymentId = await writeOfflineSnapshots(buildDir, buildId);
    await buildWorker(resolve('.'), buildId, deploymentId);
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}

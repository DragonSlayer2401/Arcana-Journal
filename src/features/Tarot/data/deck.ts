const meanings = ([
  ,
  uprightKeywords,
  uprightMeaning,
  reversedKeywords,
  reversedMeaning,
]: Entry) => ({
  upright: Object.freeze({
    keywords: Object.freeze(uprightKeywords.split(', ')),
    meaning: uprightMeaning,
  }),
  reversed: Object.freeze({
    keywords: Object.freeze(reversedKeywords.split(', ')),
    meaning: reversedMeaning,
  }),
});

const minor = (suit: Suit, entries: readonly Entry[]): TarotCard[] =>
  entries.map((entry, index) =>
    Object.freeze({
      id: `minor-${suit.toLowerCase()}-${String(index + 1).padStart(2, '0')}`,
      name: `${entry[0]} of ${suit}`,
      arcana: 'minor' as const,
      suit,
      rank: index + 1,
      ...meanings(entry),
    }),
  );

export const tarotDeck: readonly TarotCard[] = Object.freeze([
  ...major.map((entry, rank) =>
    Object.freeze({
      id: `major-${String(rank).padStart(2, '0')}`,
      name: entry[0],
      arcana: 'major' as const,
      rank,
      ...meanings(entry),
    }),
  ),
  ...minor('Wands', wands),
  ...minor('Cups', cups),
  ...minor('Swords', swords),
  ...minor('Pentacles', pentacles),
]);

export const cardById: ReadonlyMap<string, TarotCard> = new Map(
  tarotDeck.map((card) => [card.id, card]),
);
